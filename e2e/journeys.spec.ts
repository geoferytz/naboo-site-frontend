import { expect, test } from '@playwright/test';

test('visitors can browse products, compare pricing and submit forms', async ({ page }, info) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Smart Software');
  if (info.project.name === 'mobile') await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Products' }).click();
  await expect(page).toHaveURL(/\/products$/);
  await expect(page.getByRole('heading', { name: 'NABOO Sales & Management System' })).toBeVisible();
  await page.getByRole('link', { name: 'View details' }).first().click();
  await expect(page).toHaveURL(/\/products\/sales-management$/);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('NABOO Sales & Management System');
  await page.goto('/pricing');
  await expect(page.getByText('TSh 30,000', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'NABOO Hotel Management System' }).click();
  await expect(page.getByText('TSh 50,000', { exact: true })).toBeVisible();
  await page.goto('/contact');
  const inquiryForm = page.locator('form');
  await expect(inquiryForm.locator('input[name="fullName"]')).toHaveAttribute('required', '');
  await inquiryForm.locator('input[name="fullName"]').fill('Browser Visitor');
  await inquiryForm.locator('input[name="email"]').fill('browser@example.test');
  await inquiryForm.locator('select[name="subject"]').selectOption('General Inquiry');
  await inquiryForm.locator('textarea[name="message"]').fill('Please contact me about your products.');
  await inquiryForm.locator('input[name="consent"]').check();
  await inquiryForm.getByRole('button', { name: 'Send message' }).click();
  await expect(page.getByRole('status')).toContainText(/INQ-[A-F0-9]{8}/);
  await page.goto('/request-demo');
  const demoForm = page.locator('form');
  await demoForm.locator('input[name="fullName"]').fill('Browser Visitor');
  await demoForm.locator('input[name="companyName"]').fill('Browser Company');
  await demoForm.locator('input[name="email"]').fill('browser@example.test');
  await demoForm.locator('input[name="phone"]').fill('12345678');
  await demoForm.locator('select[name="productId"]').selectOption({ label: 'NABOO Sales & Management System' });
  await demoForm.locator('input[name="consent"]').check();
  await demoForm.getByRole('button', { name: 'Request my demo' }).click();
  await expect(page.getByRole('status')).toContainText(/DEMO-[A-F0-9]{8}/);
});

test('administrator can manage products, packages and requests', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop' || !process.env['ADMIN_EMAIL'] || !process.env['ADMIN_PASSWORD'], 'Local administrator credentials are required');
  await page.goto('/admin/login');
  await page.getByLabel('Email address').fill(process.env['ADMIN_EMAIL']!);
  await page.getByLabel('Password', { exact: true }).fill(process.env['ADMIN_PASSWORD']!);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page).toHaveURL(/\/admin\/dashboard$/, { timeout: 20_000 });
  await expect(page.getByText('Published products')).toBeVisible();
  const adminNav = page.getByLabel('Administration');
  await adminNav.getByRole('link', { name: 'Products', exact: true }).click();
  await page.getByRole('button', { name: 'Add product' }).click();
  const suffix = Date.now().toString(36);
  const name = `Browser Product ${suffix}`;
  const slug = `browser-${suffix}`;
  const productForm = page.locator('.admin-form');
  await productForm.getByLabel('Name', { exact: true }).fill(name);
  await productForm.getByLabel('Slug').fill(slug);
  await productForm.getByLabel('Category', { exact: true }).fill('Other');
  await productForm.getByLabel('Short description').fill('Browser verification product');
  await productForm.getByLabel('Description', { exact: true }).fill('A test product for the browser journey.');
  await productForm.getByLabel('Features (one per line)').fill('Feature one');
  await productForm.getByRole('button', { name: 'Save product' }).click();
  await expect(page.getByRole('row', { name: new RegExp(name) })).toBeVisible();
  const row = page.getByRole('row', { name: new RegExp(name) });
  await row.getByRole('button', { name: 'Publish' }).click();
  await expect(row).toContainText('PUBLISHED');
  const publicPage = await page.context().newPage();
  await publicPage.goto(`/products/${slug}`);
  await expect(publicPage.getByRole('heading', { level: 1 })).toHaveText(name);
  await publicPage.close();
  await adminNav.getByRole('link', { name: 'Pricing', exact: true }).click();
  await page.getByRole('button', { name: 'Add package' }).click();
  const packageName = `Browser Starter ${suffix}`;
  const packageForm = page.locator('.admin-form');
  await packageForm.getByRole('combobox', { name: 'Product' }).selectOption({ label: name });
  await packageForm.getByLabel('Package name').fill(packageName);
  await packageForm.getByLabel('Description', { exact: true }).fill('Browser test plan');
  await packageForm.getByLabel('Price', { exact: true }).fill('12345');
  await packageForm.getByLabel('Included features (one per line)').fill('Feature one');
  await packageForm.getByRole('button', { name: 'Save package' }).click();
  await expect(page.getByRole('row', { name: new RegExp(packageName) })).toBeVisible();
  await page.getByRole('row', { name: new RegExp(packageName) }).getByRole('button', { name: 'Edit' }).click();
  await page.locator('.admin-form').getByLabel('Price', { exact: true }).fill('23456');
  await page.locator('.admin-form').getByRole('button', { name: 'Save package' }).click();
  await expect(page.getByRole('row', { name: new RegExp(packageName) })).toContainText('23456');
  await adminNav.getByRole('link', { name: 'Demo requests', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Demo requests' })).toBeVisible();
  await page.getByRole('button', { name: 'Review' }).first().click();
  const reviewForm = page.locator('.admin-form');
  await expect(reviewForm.getByRole('button', { name: 'Save changes' })).toBeVisible();
  await reviewForm.getByLabel('Assigned to').selectOption({ index: 1 });
  await reviewForm.getByLabel('Add timestamped internal note').fill('Browser review note');
  await reviewForm.getByRole('button', { name: 'Save changes' }).click();
  await expect(reviewForm).toBeHidden();
  await adminNav.getByRole('link', { name: 'Products', exact: true }).click();
  await page.getByRole('row', { name: new RegExp(name) }).getByRole('button', { name: 'Unpublish' }).click();
  await expect(page.getByRole('row', { name: new RegExp(name) })).toContainText('DRAFT');
});
